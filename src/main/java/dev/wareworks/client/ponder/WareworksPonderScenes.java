/**
 * Which scene is shown for which item.
 * <p>
 * The component of a storyboard is the <b>item id</b>: it decides whose tooltip says "Hold [W] to Ponder" and what
 * {@code /ponder <id>} opens. Every Wareworks block therefore appears as a component of at least one scene, and blocks
 * that take part in several stories get several (scene order per component is registration order).
 * <p>
 * The tags passed to {@code addStoryBoard} only make those tags flash in the UI; membership is in
 * {@link WareworksPonderTags}.
 * <p>
 * Schematic paths resolve to {@code assets/wareworks/ponder/<path>.nbt} and are generated by
 * {@code scripts/gen_ponder_schematics.py}. Scene ids (the first argument of {@code scene.title}) must be unique
 * within the {@code wareworks} namespace, because they are the lang key prefix of the scene's texts.
 * <p>
 * The scene count per component is asserted by the {@code ponder} visual scenario
 * ({@code dev.wareworks.dev.PonderVisualScenario}), so a lost registration fails that run.
 *
 * <table>
 *   <caption>Scenes per component</caption>
 *   <tr><th>Component</th><th>Scenes</th></tr>
 *   <tr><td>stacker_crane, warehouse_rail</td><td>stacker_crane/overview, warehouse/corner,
 *       warehouse/junction, warehouse/two_cranes</td></tr>
 *   <tr><td>warehouse_interface</td><td>warehouse/interface, warehouse/filters, warehouse/storing</td></tr>
 *   <tr><td>warehouse_controller</td><td>warehouse/storing, warehouse/retrieving</td></tr>
 *   <tr><td>warehouse_input</td><td>warehouse/storing, warehouse/packages_at_the_door</td></tr>
 *   <tr><td>warehouse_output</td><td>warehouse/retrieving, warehouse/port_requesting, warehouse/port_accepting,
 *       warehouse/port_collecting, warehouse/packages_at_the_door, warehouse/ordering_to_a_door</td></tr>
 *   <tr><td>warehouse_terminal</td><td>warehouse/terminal, warehouse/requesting,
 *       warehouse/production_chain, warehouse/fluid_bay, warehouse/ordering_to_a_door,
 *       warehouse/fluid_request</td></tr>
 *   <tr><td>warehouse_production</td><td>warehouse/production, warehouse/port_collecting,
 *       warehouse/production_chain, warehouse/crafter_feeder</td></tr>
 *   <tr><td>warehouse_crafter_feeder</td><td>warehouse/crafter_feeder</td></tr>
 *   <tr><td>warehouse_stock_keeper</td><td>warehouse/stock_rules, warehouse/restocking,
 *       warehouse/port_accepting</td></tr>
 *   <tr><td>rack_bay_wood, rack_bay_andesite, rack_bay_brass</td><td>warehouse/rack_bay, warehouse/rack_wall,
 *       warehouse/bays_in_an_aisle</td></tr>
 *   <tr><td>fluid_bay_copper, fluid_bay_brass</td><td>warehouse/fluid_bay, warehouse/fluid_request</td></tr>
 *   <tr><td>hand_truck</td><td>hand_truck/carrying</td></tr>
 * </table>
 */
public final class WareworksPonderScenes {
    private WareworksPonderScenes() {
    }

    public static void register(PonderSceneRegistrationHelper<ResourceLocation> helper) {
        PonderSceneRegistrationHelper<ItemProviderEntry<?, ?>> scenes = helper.withKeyFunction(RegistryEntry::getId);

        scenes.forComponents(WareworksBlocks.STACKER_CRANE, WareworksBlocks.WAREHOUSE_RAIL)
                .addStoryBoard("stacker_crane/overview", CraneScenes::overview,
                        WareworksPonderTags.WAREHOUSE, AllCreatePonderTags.KINETIC_APPLIANCES);

        scenes.forComponents(WareworksBlocks.WAREHOUSE_INTERFACE)
                .addStoryBoard("warehouse/interface", WarehouseScenes::warehouseInterface,
                        WareworksPonderTags.WAREHOUSE);

        scenes.forComponents(WareworksBlocks.WAREHOUSE_INTERFACE)
                .addStoryBoard("warehouse/filters", WarehouseScenes::storageFilters,
                        WareworksPonderTags.WAREHOUSE);

        scenes.forComponents(WareworksBlocks.WAREHOUSE_INPUT, WareworksBlocks.WAREHOUSE_CONTROLLER,
                        WareworksBlocks.WAREHOUSE_INTERFACE)
                .addStoryBoard("warehouse/storing", WarehouseScenes::storing,
                        WareworksPonderTags.WAREHOUSE, AllCreatePonderTags.LOGISTICS);

        scenes.forComponents(WareworksBlocks.WAREHOUSE_OUTPUT, WareworksBlocks.WAREHOUSE_CONTROLLER)
                .addStoryBoard("warehouse/retrieving", WarehouseScenes::retrieving,
                        WareworksPonderTags.WAREHOUSE, AllCreatePonderTags.LOGISTICS);

        scenes.forComponents(WareworksBlocks.WAREHOUSE_TERMINAL)
                .addStoryBoard("warehouse/terminal", TerminalScenes::placing,
                        WareworksPonderTags.WAREHOUSE);

        scenes.forComponents(WareworksBlocks.WAREHOUSE_TERMINAL)
                .addStoryBoard("warehouse/requesting", TerminalScenes::requesting,
                        WareworksPonderTags.WAREHOUSE, AllCreatePonderTags.LOGISTICS);

        scenes.forComponents(WareworksBlocks.WAREHOUSE_PRODUCTION)
                .addStoryBoard("warehouse/production", ProductionScenes::production,
                        WareworksPonderTags.WAREHOUSE, AllCreatePonderTags.LOGISTICS);

        scenes.forComponents(WareworksBlocks.WAREHOUSE_STOCK_KEEPER)
                .addStoryBoard("warehouse/stock_rules", StockRuleScenes::stockRules,
                        WareworksPonderTags.WAREHOUSE, AllCreatePonderTags.LOGISTICS);

        scenes.forComponents(WareworksBlocks.WAREHOUSE_STOCK_KEEPER)
                .addStoryBoard("warehouse/restocking", StockRuleScenes::restocking,
                        WareworksPonderTags.WAREHOUSE, AllCreatePonderTags.LOGISTICS);

        // The two port scenes come last on purpose (M17, issue #12): scene order per component is registration order,
        // so registering them here leaves warehouse/retrieving the first thing a warehouse output shows and
        // warehouse/stock_rules the first thing a stock keeper shows, with the port as the answer that follows.
        scenes.forComponents(WareworksBlocks.WAREHOUSE_OUTPUT)
                .addStoryBoard("warehouse/port_requesting", PortScenes::requesting,
                        WareworksPonderTags.WAREHOUSE, AllCreatePonderTags.LOGISTICS);

        // Also a scene of the stock keeper: a maximum that makes a warehouse input back up (warehouse/stock_rules) is
        // exactly what an accepting port answers, and a player who read the one needs to find the other.
        scenes.forComponents(WareworksBlocks.WAREHOUSE_OUTPUT, WareworksBlocks.WAREHOUSE_STOCK_KEEPER)
                .addStoryBoard("warehouse/port_accepting", PortScenes::accepting,
                        WareworksPonderTags.WAREHOUSE, AllCreatePonderTags.LOGISTICS);

        // The third direction (M18, issue #13), last again for the same reason. Also a scene of the <b>production
        // station</b>: closing the loop — the crane brings the ingredients and takes the product back — is exactly what
        // that block's story needs, and a player who read warehouse/production has to find this one.
        scenes.forComponents(WareworksBlocks.WAREHOUSE_OUTPUT, WareworksBlocks.WAREHOUSE_PRODUCTION)
                .addStoryBoard("warehouse/port_collecting", PortScenes::collecting,
                        WareworksPonderTags.WAREHOUSE, AllCreatePonderTags.LOGISTICS);

        // Recursive production (M20, issue #4, ADR-032), and registered last for the same reason as the port scenes: it
        // is the answer that follows warehouse/production and warehouse/requesting, not the first thing either block
        // should show. It belongs to <b>both</b> — the chain is planned by a click at a terminal and run at the
        // stations — so a player who met one half finds the other.
        scenes.forComponents(WareworksBlocks.WAREHOUSE_PRODUCTION, WareworksBlocks.WAREHOUSE_TERMINAL)
                .addStoryBoard("warehouse/production_chain", ProductionScenes::chain,
                        WareworksPonderTags.WAREHOUSE, AllCreatePonderTags.LOGISTICS);

        // Rails around a corner (M21, issue #1, ADR-033), and last for the same reason as the scenes above: a player
        // meets "what a stacker crane is" first and "and the rails may bend" after it. It belongs to <b>both</b> the
        // rail and the crane — the rails decide where the warehouse goes, the machine is what turns on them — so a
        // player who picked up either one finds it.
        scenes.forComponents(WareworksBlocks.WAREHOUSE_RAIL, WareworksBlocks.STACKER_CRANE)
                .addStoryBoard("warehouse/corner", NetworkScenes::corner,
                        WareworksPonderTags.WAREHOUSE, AllCreatePonderTags.KINETIC_APPLIANCES);

        // Rails that split (M22, issue #2, ADR-035), and after the corner for the same reason the corner comes after
        // the overview: a player meets "what a stacker crane is", then "the rails may bend", then "and they may
        // split". It belongs to the same two components, because it is the same two blocks that make it happen.
        scenes.forComponents(WareworksBlocks.WAREHOUSE_RAIL, WareworksBlocks.STACKER_CRANE)
                .addStoryBoard("warehouse/junction", NetworkScenes::junction,
                        WareworksPonderTags.WAREHOUSE, AllCreatePonderTags.KINETIC_APPLIANCES);

        // Several cranes on one warehouse (issue #14, ADR-075), after the junction for the same reason the junction
        // comes after the corner: a player meets "the rails may split" first and "and a second machine may share them"
        // after it, and the scene's stage is the junction scene's comb. It belongs to the same two components, because
        // the second crane is a second dock and the rails are what the two share. Registering it here moves no scene of
        // any other block.
        scenes.forComponents(WareworksBlocks.STACKER_CRANE, WareworksBlocks.WAREHOUSE_RAIL)
                .addStoryBoard("warehouse/two_cranes", TwoCraneScenes::twoCranes,
                        WareworksPonderTags.WAREHOUSE, AllCreatePonderTags.KINETIC_APPLIANCES);

        // Packages at a door (M26, issue #18, ADR-040), and last for the same reason as every scene above: a player
        // meets "a port hands items out" and "an input takes items in" first, and "and a Create Packager can box them
        // on the way" after. It belongs to <b>both</b> doors — the build is the same block on either side of the
        // warehouse, and which station its back touches is the whole lesson — so a player who met one finds the other.
        scenes.forComponents(WareworksBlocks.WAREHOUSE_OUTPUT, WareworksBlocks.WAREHOUSE_INPUT)
                .addStoryBoard("warehouse/packages_at_the_door", PackageScenes::packagesAtTheDoor,
                        WareworksPonderTags.WAREHOUSE, AllCreatePonderTags.LOGISTICS);

        // The rack bay (M28, issue #20, ADR-048), and the one block of this mod whose scenes are deliberately NOT in
        // "warehouse first" order: a wooden bay needs no machine to craft and many players meet it as a better barrel
        // long before they own a crane, so the standalone block comes first, the wall it grows into second, and the
        // warehouse that adopts it last. All three tiers carry all three scenes, because the tier is the block and a
        // player holding a brass bay has to find the same three lessons as one holding a wooden one.
        scenes.forComponents(WareworksBlocks.RACK_BAY_WOOD, WareworksBlocks.RACK_BAY_ANDESITE,
                        WareworksBlocks.RACK_BAY_BRASS)
                .addStoryBoard("warehouse/rack_bay", RackBayScenes::rackBay,
                        WareworksPonderTags.WAREHOUSE, AllCreatePonderTags.LOGISTICS);

        scenes.forComponents(WareworksBlocks.RACK_BAY_WOOD, WareworksBlocks.RACK_BAY_ANDESITE,
                        WareworksBlocks.RACK_BAY_BRASS)
                .addStoryBoard("warehouse/rack_wall", RackBayScenes::rackWall,
                        WareworksPonderTags.WAREHOUSE);

        scenes.forComponents(WareworksBlocks.RACK_BAY_WOOD, WareworksBlocks.RACK_BAY_ANDESITE,
                        WareworksBlocks.RACK_BAY_BRASS)
                .addStoryBoard("warehouse/bays_in_an_aisle", RackBayScenes::baysInAnAisle,
                        WareworksPonderTags.WAREHOUSE, AllCreatePonderTags.LOGISTICS);

        // The fluid bay (M30, issue #21, ADR-051..ADR-055). One scene for both tiers, because the tier is the block and
        // what a player cannot guess is the same for copper and brass: what becomes of the container. Also a scene of
        // the <b>warehouse terminal</b> — a player holding a stocked warehouse looks for lava in the stock list and
        // finds buckets, and the closing beats are where the fluid really goes in and out. Asking for the fluid back
        // (M31) is a scene of its own, warehouse/fluid_request, registered last below.
        scenes.forComponents(WareworksBlocks.FLUID_BAY_COPPER, WareworksBlocks.FLUID_BAY_BRASS,
                        WareworksBlocks.WAREHOUSE_TERMINAL)
                .addStoryBoard("warehouse/fluid_bay", FluidBayScenes::fluidsTravelInContainers,
                        WareworksPonderTags.WAREHOUSE, AllCreatePonderTags.FLUIDS);

        // Ordering to a package door (M27, issue #18 second half, ADR-065), and last for the same reason as every scene
        // above: a player meets "requesting at a terminal" and "a Packager at a port" first, and "and a click can go to
        // that door" after both. It belongs to <b>both</b> the terminal, where the door is chosen, and the output, which
        // is the door, so a player who met either half finds the other. Registered after warehouse/fluid_bay, so no
        // scene of either block changes its place (ADR-016).
        scenes.forComponents(WareworksBlocks.WAREHOUSE_TERMINAL, WareworksBlocks.WAREHOUSE_OUTPUT)
                .addStoryBoard("warehouse/ordering_to_a_door", PackageScenes::orderingToADoor,
                        WareworksPonderTags.WAREHOUSE, AllCreatePonderTags.LOGISTICS);

        // The Crafter Feeder (issue #34, ADR-067), and last for the same reason as every scene above: a player meets
        // "a station feeds your machines" and "chains of orders" first, and "and a vanilla Crafter can be that machine"
        // after. It belongs to <b>both</b> the feeder and the production station, because the feeder is that
        // station's machine and its patterns are the station's; registered last, so no scene of the station moves.
        scenes.forComponents(WareworksBlocks.WAREHOUSE_CRAFTER_FEEDER, WareworksBlocks.WAREHOUSE_PRODUCTION)
                .addStoryBoard("warehouse/crafter_feeder", CrafterFeederScenes::feeder,
                        WareworksPonderTags.WAREHOUSE, AllCreatePonderTags.KINETIC_APPLIANCES);

        // Asking the warehouse for fluid (M31, issue #21, ADR-073), and last for the same reason as every scene above:
        // a player meets "fluids travel in containers" and "requesting at a terminal" first, and "and the terminal can
        // ask for the fluid itself" after both. It belongs to both fluid bays, where the fill happens, and to the
        // terminal, where the fluid row is clicked; registered last, so no scene of either block moves (ADR-016).
        scenes.forComponents(WareworksBlocks.FLUID_BAY_COPPER, WareworksBlocks.FLUID_BAY_BRASS,
                        WareworksBlocks.WAREHOUSE_TERMINAL)
                .addStoryBoard("warehouse/fluid_request", FluidBayScenes::askingForFluid,
                        WareworksPonderTags.WAREHOUSE, AllCreatePonderTags.FLUIDS);

        // The hand truck (issue #37, ADR-070): an item rather than a warehouse block, so it carries no Wareworks tag; its
        // one scene is load, walk slowly, set down.
        scenes.forComponents(WareworksItems.HAND_TRUCK)
                .addStoryBoard("hand_truck/carrying", HandTruckScenes::carrying);
    }
}
